// Reproducible server-only GeoTIFF adapter for Supabase Edge (no Node vm/Pool).
import {build} from 'esbuild';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';

const root=fileURLToPath(new URL('./',import.meta.url)),out=resolve(root,'vendor');
const packages=['geotiff','@petamoriken/float16','lerc','pako','parse-headers','quick-lru','web-worker','xml-utils','zstddec'];
await mkdir(out,{recursive:true});
const result=await build({
 stdin:{contents:"export {fromCustomClient,BaseClient,BaseResponse,BaseDecoder,addDecoder} from 'geotiff';",resolveDir:root,sourcefile:'terrain-geotiff-entry.mjs'},
 outfile:resolve(out,'geotiff-terrain.mjs'),bundle:true,format:'esm',platform:'browser',target:'es2022',
 write:false,minify:true,metafile:true,legalComments:'external',
 banner:{js:'// GeoTIFF 3.0.5; generated by node satellite-backend/build-terrain-geotiff.mjs. See GEOTIFF-LICENSES.txt.'},
});
const code=result.outputFiles.find(file=>file.path.endsWith('/geotiff-terrain.mjs'));
const output=Object.values(result.metafile.outputs).find(file=>file.entryPoint?.endsWith('terrain-geotiff-entry.mjs'));
if(!code||!output||output.imports.length||/node:vm|worker_threads|require\(["'](?:fs|vm|http|https|url)["']/.test(code.text))throw Error('GeoTIFF bundle contains an unsupported external or Node dependency.');
if(Object.entries(output.inputs).some(([name,info])=>/\/(?:pool\.js|worker\/|client\/http\.js|source\/file\.js)/.test(name)&&info.bytesInOutput>0))throw Error('Server-only raster bundle must not include worker pools or file/network clients.');
for(const file of result.outputFiles)await writeFile(file.path,file.contents);

const notices=['UR Smart server-only GeoTIFF dependency notices.\n\nThis file records the source packages used for the reproducible browser-platform ESM bundle. All are pinned by satellite-backend/package-lock.json; the bundle exports only the bounded raster reader adapter and has no external imports. Some package paths are tree-shaken from the output. Original licenses follow.'];
for(const name of packages){
 const base=resolve(root,'node_modules',name),pkg=JSON.parse(await readFile(resolve(base,'package.json'),'utf8'));
 let license='';
 for(const file of ['LICENSE','license','LICENSE.txt','LICENSE.md']){try{license=await readFile(resolve(base,file),'utf8');break;}catch{}}
 if(!license){
  if(name==='parse-headers')license=(await readFile(resolve(base,'readme.md'),'utf8')).split('## Licence')[1];
  else if(name==='lerc')license=(await readFile(resolve(base,'README.md'),'utf8')).split('## Licensing')[1];
  else throw Error('Missing dependency license: '+name);
 }
 notices.push('\n\n'+name+' '+pkg.version+' — '+pkg.license+'\n'+(typeof pkg.repository==='string'?pkg.repository:pkg.repository?.url||'')+'\n\n'+license.trim());
}
await writeFile(resolve(out,'GEOTIFF-LICENSES.txt'),notices.join('')+'\n');
console.log(JSON.stringify({bundle:'satellite-backend/vendor/geotiff-terrain.mjs',bytes:code.contents.length,externalImports:output.imports.length}));
